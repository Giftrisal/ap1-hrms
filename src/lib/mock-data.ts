// Generates today's initial attendance records matching real office timings
export function generateTodayAttendance(): DailyAttendance[] {
  const today = new Date().toISOString().split('T')[0];
  
  return initialEmployees.map((emp, index) => {
    let status: DailyAttendance['status'] = 'PRESENT';
    let in_time: string | undefined = undefined;
    let out_time: string | undefined = undefined;
    let late_minutes = 0;
    let worked_hours = 0;

    if (index < 23) {
      // Present on time (8:48 to 9:12 AM)
      const minute = (index * 2) % 15;
      const inDate = new Date(`${today}T08:55:00`);
      inDate.setMinutes(50 + minute);
      in_time = inDate.toISOString();
      const outDate = new Date(`${today}T17:15:00`);
      out_time = outDate.toISOString();
      worked_hours = 8.2;
      status = 'PRESENT';
    } else if (index < 28) {
      // Late arrivals (9:20 to 9:48 AM)
      late_minutes = 20 + (index - 23) * 7;
      const inDate = new Date(`${today}T09:00:00`);
      inDate.setMinutes(late_minutes);
      in_time = inDate.toISOString();
      worked_hours = 7.5;
      status = 'LATE';
    } else if (index === 28) {
      // Half Day
      in_time = `${today}T11:45:00.000Z`;
      late_minutes = 165;
      worked_hours = 4.5;
      status = 'HALF_DAY';
    } else if (index === 29) {
      // On approved leave
      status = 'ON_LEAVE';
    } else {
      // Absent
      status = 'ABSENT';
    }

    return {
      id: `att-${emp.id}-${today}`,
      employee_id: emp.id,
      employee_name: emp.full_name,
      employee_pin: emp.biometric_pin,
      employee_photo: emp.photo_url,
      department_name: emp.department_name,
      designation: emp.designation,
      date: today,
      in_time,
      out_time,
      status,
      late_minutes,
      early_exit_minutes: 0,
      overtime_minutes: index === 3 ? 60 : 0,
      worked_hours,
      remarks: status === 'LATE' ? `Late arrival (${late_minutes}m)` : undefined,
      source: 'ZKTeco_LAN'
    };
  });
}

